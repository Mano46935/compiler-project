"""Deterministic HTML/CSS generation for the validated Review 1 subset."""

from html import escape
from pathlib import Path

from .model import CompilationResult, Element

COLORS = {
    "blue": "#2b6cb0", "red": "#b91c1c", "green": "#166534",
    "black": "#111827", "white": "#ffffff",
}
SIZES = {"small": "0.875rem", "medium": "1.125rem", "big": "2.5rem"}
TAGS = {"heading": "h1", "paragraph": "p", "button": "button"}
BASE_CSS = """/* Generated by Text2Web (Review 1). Contrast is not validated. */
* { box-sizing: border-box; }
body { margin: 0; background: #ffffff; color: #111827; font-family: Arial, sans-serif; }
.page { max-width: 960px; margin: 0 auto; padding: 40px 24px; }
h1 { font-size: 2rem; margin: 0 0 20px; }
p { line-height: 1.6; margin: 0 0 20px; white-space: pre-wrap; }
button { font: inherit; padding: 12px 20px; border: 1px solid #64748b; border-radius: 6px; }
"""


def generate(title: str, elements: list[Element]) -> tuple[str, str]:
    markup = []
    rules = []
    for element in elements:
        tag = TAGS[element.type]
        attributes = f' id="{element.id}"'
        if tag == "button":
            attributes += ' type="button"'
        markup.append(f"    <{tag}{attributes}>{escape(element.text)}</{tag}>")
        declarations = []
        props = element.properties
        if "color" in props:
            color = COLORS[props["color"]]
            if tag == "button":
                foreground = "#111827" if props["color"] == "white" else "#ffffff"
                declarations.extend([f"background-color: {color}", f"color: {foreground}"])
            else:
                declarations.append(f"color: {color}")
        if "size" in props:
            declarations.append(f"font-size: {SIZES[props['size']]}")
        if props.get("font-weight") == "bold":
            declarations.append("font-weight: 700")
        if declarations:
            rules.append(f"#{element.id} {{ {'; '.join(declarations)}; }}")
    body = "\n".join(markup)
    html = f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{escape(title)}</title>
  <link rel="stylesheet" href="style.css">
</head>
<body>
  <main class="page">
{body}
  </main>
</body>
</html>
'''
    return html, BASE_CSS + "\n".join(rules) + "\n"


def write_output(result: CompilationResult, directory: Path, *, overwrite: bool = False) -> None:
    """Write only successful builds; refuse existing output files by default."""
    if not result.success:
        raise ValueError("Cannot write output for a failed compilation.")
    directory = Path(directory)
    destinations = [directory / "index.html", directory / "style.css"]
    if not overwrite and any(path.exists() for path in destinations):
        raise FileExistsError("Output files already exist. Choose another folder or use --force.")
    directory.mkdir(parents=True, exist_ok=True)
    for path, contents in zip(destinations, [result.html, result.css]):
        path.write_text(contents, encoding="utf-8", newline="\n")
